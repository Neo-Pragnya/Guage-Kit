"""Generate docs/reference/metrics.md from the metric registry (tests/test_docs.py keeps it in sync).

Usage: python scripts/gen_metric_docs.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

from guage_kit.metrics.registry import list_metrics

OUT = Path(__file__).resolve().parents[1] / "docs" / "reference" / "metrics.md"

FAMILY_TITLES = {
    "text": "Text (reference-based)",
    "semantic": "Semantic similarity",
    "rag": "RAG: grounding and context",
    "retrieval": "Retrieval (ranked ids)",
    "classification": "Classification",
    "calibration": "Calibration",
    "embeddings": "Embedding models",
    "structured": "Structured output",
    "safety": "Safety and responsibility",
    "agent": "Agents and tool use",
    "runtime": "Runtime and cost",
    "judge": "LLM judge",
}


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    items = list_metrics()
    native = [m for m in items if m["source"] != "ananke-plexus"]
    ananke = [m for m in items if m["source"] == "ananke-plexus"]
    lines = [
        "---",
        "title: Metric catalogue",
        "description: Every metric Guage Kit ships, with its family, level, required fields and parameters (generated).",
        "---",
        "",
        "# Metric catalogue",
        "",
        "> [!NOTE]",
        "> Generated by `scripts/gen_metric_docs.py` from the metric registry. `guage metrics list` and",
        "> `guage metrics show <name>` print the same information for the installed version.",
        "",
        f"Guage Kit has **{len(native)} native metrics** and exposes **{len(ananke)} Ananke Plexus evaluators** as",
        "metrics, for a total of " + str(len(items)) + ". ↑ means higher is better, ↓ lower is better. *Sample* metrics score",
        "each sample and report the mean with a bootstrap interval; *corpus* metrics are computed over the whole set",
        "(their interval comes from resampling the samples).",
        "",
    ]
    families: dict[str, list[dict]] = {}
    for m in native:
        families.setdefault(m["family"], []).append(m)
    order = [f for f in FAMILY_TITLES if f in families] + sorted(f for f in families if f not in FAMILY_TITLES)
    lines.append("## Native metrics\n")
    for fam in order:
        lines += [f"### {FAMILY_TITLES.get(fam, fam.title())}", "", "| metric | level | needs | parameters | description |", "| --- | --- | --- | --- | --- |"]
        for m in families[fam]:
            needs = ", ".join(f"`{f}`" for f in m["requires"])
            if m["requires_any"]:
                needs += (", " if needs else "") + " or ".join(f"`{f}`" for f in m["requires_any"])
            if m["needs_judge"]:
                needs += (", " if needs else "") + "a judge"
            params = ", ".join(f"`{k}={v!r}`" for k, v in m["params"].items()) or "–"
            arrow = "↑" if m["higher_is_better"] else "↓"
            desc = m["description"] + (f" *Ref: {m['reference']}.*" if m["reference"] else "") + (f" Extra: `{m['extra']}`." if m["extra"] else "")
            lines.append(f"| `{m['name']}` {arrow} | {m['level']} | {needs or '–'} | {_cell(params)} | {_cell(desc)} |")
        lines.append("")
    lines += [
        "## Ananke Plexus evaluators",
        "",
        "Discovered from the installed `ananke-plexus` and run on each sample's trace (recorded, or built from its tool",
        "calls, contexts and usage). Arguments marked *required* come from metric `params`, the sample's",
        "`metadata.ananke`, its `expected_tool_calls`, or `metadata.<argument>`; see [agents](../guides/agents.md).",
        "",
    ]
    by_dim: dict[str, list[dict]] = {}
    for m in ananke:
        by_dim.setdefault(m["family"].removeprefix("ananke."), []).append(m)
    for dim in sorted(by_dim):
        lines += [f"### {dim.replace('_', ' ').title()}", "", "| metric | arguments |", "| --- | --- |"]
        for m in by_dim[dim]:
            args = ", ".join(f"`{k}`" + (" *(required)*" if v is None else f"=`{v!r}`") for k, v in m["params"].items()) or "–"
            lines.append(f"| `{m['name']}` | {_cell(args)} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/reference/metrics.md is out of date: run python scripts/gen_metric_docs.py")
            sys.exit(1)
        print("metrics.md is up to date")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT}")
