#!/usr/bin/env python3
"""Generate a package's PyPI long description from the repository README, so one README serves GitHub and PyPI.

PyPI renders GitHub-flavoured Markdown but cannot follow relative links, does not render Mermaid, alerts, math or
<picture>, and an SVG must come from a server that sends `image/svg+xml` (raw.githubusercontent.com sends text/plain,
so animated SVGs must be served from GitHub Pages or another static host). This script:

  * rewrites relative image paths under the mapped folders to the hosted URLs (e.g. assets/readme/ → Pages /readme/);
  * rewrites every other relative link to the file on GitHub (blob for files, tree for folders);
  * converts GitHub-only syntax: <picture> → its <img>, ```mermaid → a link to the README on GitHub,
    > [!NOTE] alerts → bold quote headers, ```math → ```text, inline $…$ → `…` (never inside code fences);
  * prepends a "generated, do not edit" header;
  * `--check` exits 1 when the PyPI copy is stale (wire it into CI or `make docs-check`).

    python pypi_readme.py --repo https://github.com/ORG/REPO --site https://org.github.io/REPO \
        --map assets/readme/=readme/ --map examples/gallery/=gallery/ \
        --src README.md --dst python/README.md [--branch main] [--check]

Settings can also live in pyproject.toml under [tool.pypi-readme] (keys: repo, site, src, dst, branch, map = {…}).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ALERTS = {"NOTE": "📝 Note", "TIP": "💡 Tip", "IMPORTANT": "❗ Important", "WARNING": "⚠️ Warning", "CAUTION": "🛑 Caution"}


def load_config(root: Path) -> dict:
    py = root / "pyproject.toml"
    if not py.exists():
        return {}
    try:
        import tomllib
    except ModuleNotFoundError:  # Python < 3.11
        return {}
    return tomllib.loads(py.read_text(encoding="utf-8")).get("tool", {}).get("pypi-readme", {})


def pypi_only(text: str, repo: str) -> str:
    """GitHub-only Markdown → what PyPI renders. Code fences are left untouched."""
    text = re.sub(r"<picture>.*?(<img [^>]*/?>).*?</picture>", r"\1", text, flags=re.S)
    text = re.sub(r"```mermaid\n.*?```", f"> 📊 *A diagram is here on GitHub: [view the README there]({repo}#readme).*", text, flags=re.S)
    text = re.sub(r"^> \[!(\w+)\]\s*$", lambda m: f"> **{ALERTS.get(m.group(1), m.group(1).title())}**  ", text, flags=re.M)
    text = text.replace("```math\n", "```text\n")
    parts = re.split(r"(```.*?```)", text, flags=re.S)
    for i in range(0, len(parts), 2):  # outside fences only
        parts[i] = re.sub(r"(?<![\w`$])\$(?!\()([^$`\n]+?)\$",
                          lambda m: "`" + re.sub(r"\\text\{([^}]*)\}", r"\1", m.group(1)).replace("{", "").replace("}", "") + "`", parts[i])
    return "".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", default=".")
    ap.add_argument("--repo"), ap.add_argument("--site"), ap.add_argument("--src"), ap.add_argument("--dst"), ap.add_argument("--branch")
    ap.add_argument("--map", action="append", default=[], help="LOCAL_PREFIX=SITE_SUBPATH, e.g. assets/readme/=readme/")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    root = Path(a.root).resolve()
    cfg = load_config(root)
    repo = (a.repo or cfg.get("repo") or "").rstrip("/")
    site = (a.site or cfg.get("site") or "").rstrip("/")
    src, dst = root / (a.src or cfg.get("src", "README.md")), root / (a.dst or cfg.get("dst", "README.pypi.md"))
    branch = a.branch or cfg.get("branch", "main")
    maps = dict(cfg.get("map", {}))
    for m in a.map:
        k, v = m.split("=", 1)
        maps[k] = v
    if not repo:
        ap.error("--repo (or [tool.pypi-readme] repo) is required")
    if maps and not site:
        ap.error("--site is required when folders are mapped to the site")

    def absolute(path: str) -> str:
        if re.match(r"^(https?:|mailto:|#|data:)", path):
            return path
        for prefix, sub in maps.items():
            if path.startswith(prefix):
                return f"{site}/{sub}{path[len(prefix):]}"
        target = path.split("#", 1)[0]
        kind = "tree" if (root / target).is_dir() else "blob"
        return f"{repo}/{kind}/{branch}/{path}"

    text = pypi_only(src.read_text(encoding="utf-8"), repo)
    text = re.sub(r'(src|href|srcset)="([^"]+)"', lambda m: f'{m.group(1)}="{absolute(m.group(2))}"', text)
    text = re.sub(r"\]\(([^)\s]+)\)", lambda m: f"]({absolute(m.group(1))})", text)
    want = f"<!-- Generated by pypi_readme.py from {src.name}. Do not edit by hand. -->\n\n" + text
    rel = dst.relative_to(root) if dst.is_relative_to(root) else dst
    if a.check:
        if not dst.exists() or dst.read_text(encoding="utf-8") != want:
            print(f"{rel} is stale: run pypi_readme.py")
            return 1
        print("pypi readme ok")
        return 0
    dst.write_text(want, encoding="utf-8")
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
